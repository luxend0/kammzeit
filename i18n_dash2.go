// money formatiert Cent als Preis: Deutsch wie die Template-Funktion euro
// ("45,00 €"), Englisch für den EU-Markt "€45.00".
// ponytail: ohne Tausendertrennzeichen, wie euro.
func money(lang string, cents int64) string {
	if lang == "en" {
		return fmt.Sprintf("€%d.%02d", cents/100, cents%100)
	}
	return fmt.Sprintf("%d,%02d €", cents/100, cents%100)
}

